// src/utils/taskReport.ts — 本轮任务汇总(计数 / 明细 / 文案)
// 职责:模块加载时即订阅 taskBus(本模块唯一的副作用,无取消入口),累加本轮结果;
//       提供纯函数生成计数条文字、通知文案与日志摘要。不依赖 UI 与 Android API。
import { 订阅, 任务事件, 任务结束事件, 整轮结束事件, 战斗结果事件 } from './taskBus'

export interface 明细项 {
  状态: '跳过' | '异常'
  名: string
  原因: string          // 原始值;事件未带原因时已在上游归一为空串,兜底文案由格式化函数负责
  服?: string
}

export interface 汇总结果 {
  成功: number
  跳过: number
  异常: number
  条数: number          // 恒等于 成功 + 跳过 + 异常(不含战斗结果,战斗不是"任务")
  明细: 明细项[]        // 跳过与异常,按发生顺序
  战斗成功: number      // 仅顶层战斗产出;与 成功/跳过/异常 不会同时有值(两个模式互斥)
  战斗失败: number
  模式: '日常' | '战斗' // 由「本轮开始」带入,决定计数条格式(计数全 0 时也要能选对样式)
}

function 空汇总(): 汇总结果 {
  return { 成功: 0, 跳过: 0, 异常: 0, 条数: 0, 明细: [], 战斗成功: 0, 战斗失败: 0, 模式: '日常' }
}

var 当前: 汇总结果 = 空汇总()

/** 本轮汇总对象本身(活引用,非副本)。两条使用约束:
 *  1) 只读:勿改字段、勿用 明细.sort() 之类原地方法,会污染后续计数与明细顺序;
 *  2) 勿缓存:重置本轮 与「本轮开始」会整体换新对象,早先拿到的引用会停在旧数据上不再更新。 */
export function 本轮汇总(): 汇总结果 {
  return 当前
}

/** 清空本轮计数与明细(由「本轮开始」事件自动触发,也可手工调用,仅诊断脚本会用)。
 *  模式缺省按日常 —— 不传模式的调用方(如诊断脚本)拿到的就是日常格式 */
export function 重置本轮(模式?: '日常' | '战斗'): void {
  当前 = 空汇总()
  当前.模式 = 模式 ? 模式 : '日常'
}

function 记录(e: 任务结束事件): void {
  当前.条数++
  if (e.状态 === '成功') {
    当前.成功++
    return
  }
  if (e.状态 === '跳过') 当前.跳过++
  else 当前.异常++
  当前.明细.push({
    状态: e.状态,
    名: e.名,
    原因: e.原因 ? e.原因 : '',
    服: e.服,
  })
}

/** 战斗结果只计数,不进明细也不计入 条数——它不是"任务",没有跳过/异常语义 */
function 记录战斗结果(e: 战斗结果事件): void {
  if (e.成功) 当前.战斗成功++
  else 当前.战斗失败++
}

// 订阅在模块加载时完成;顺序保证:taskNotifier 会 import 本模块,ES 模块先求值依赖,
// 因此订阅顺序恒为 taskReport 先于 taskNotifier —— notifier 读到的汇总总是已累加的最新值。
// 不保存取消句柄:本模块的订阅与脚本同生命周期,没有取消场景(规格「已知限制 4」)。
订阅(function (e: 任务事件): void {
  try {
    if (e.类型 === '本轮开始') {
      重置本轮(e.模式)
      return
    }
    if (e.类型 === '任务结束') {
      记录(e)
      return
    }
    if (e.类型 === '战斗结果') {
      记录战斗结果(e)
      return
    }
    if (e.类型 === '整轮结束') {
      打印摘要(e)
    }
  } catch (err: any) {
    console.log('[汇总] 处理事件失败: ' + (err && err.message ? err.message : err))
  }
})

/** 整轮结束:把摘要写进日志(不依赖 taskNotifier,通知开关关闭时也要留档) */
function 打印摘要(e: 整轮结束事件): void {
  console.log(格式化摘要(本轮汇总(), e.结果))
}

/** 通知明细每节最多列出的条数,超出折叠为一行提示(结果页不受此限,见 格式化完整明细) */
var 每节上限 = 5

/** 计数条文字。
 *  日常模式 "✅ 12  ⏭ 3  ❌ 2";战斗模式 "✅ 12  ❌ 2"(胜/负,无跳过项)。
 *  格式由 模式 决定,而不是"有没有战斗结果"——否则战斗模式开局到首局结算之间会错显日常格式。
 *  保留"有战斗结果即切战斗段"作兜底:日常轮里混进战斗结果(不该发生)时也不至于两种计数叠在一起。 */
export function 格式化计数条(汇总: 汇总结果): string {
  if (汇总.模式 === '战斗' || 汇总.战斗成功 + 汇总.战斗失败 > 0) {
    return '✅ ' + 汇总.战斗成功 + '  ❌ ' + 汇总.战斗失败
  }
  return '✅ ' + 汇总.成功 + '  ⏭ ' + 汇总.跳过 + '  ❌ ' + 汇总.异常
}

/** 通知标题,如 "日常完成 ✅12 ⏭3 ❌2" */
export function 格式化通知标题(汇总: 汇总结果, 结果: '完成' | '已停止'): string {
  var 前缀 = 结果 === '完成' ? '日常完成' : '日常已停止'
  return 前缀 + ' ✅' + 汇总.成功 + ' ⏭' + 汇总.跳过 + ' ❌' + 汇总.异常
}

/** 通知折叠态正文,如 "成功 12 | 跳过 3 | 异常 2 | 合计 17" */
export function 格式化通知正文(汇总: 汇总结果): string {
  return '成功 ' + 汇总.成功 + ' | 跳过 ' + 汇总.跳过 + ' | 异常 ' + 汇总.异常 + ' | 合计 ' + 汇总.条数
}

/** 通知展开态明细;无跳过与异常时返回空串(调用方据此决定是否设置 BigTextStyle) */
export function 格式化通知明细(汇总: 汇总结果): string {
  return 拼接明细(汇总, 每节上限)
}

/** 结果页明细:全量列出不折叠;无跳过与异常时返回空串(调用方据此显示占位文案) */
export function 格式化完整明细(汇总: 汇总结果): string {
  return 拼接明细(汇总, -1)
}

/** 上限为 -1 时不折叠 */
function 拼接明细(汇总: 汇总结果, 上限: number): string {
  var 跳过项 = 取明细(汇总, '跳过')
  var 异常项 = 取明细(汇总, '异常')
  if (跳过项.length === 0 && 异常项.length === 0) return ''
  var 行: string[] = []
  if (跳过项.length > 0) 追加节(行, '跳过', 跳过项, 上限)
  if (异常项.length > 0) 追加节(行, '异常', 异常项, 上限)
  return 行.join('\n')
}

/** 整轮结束时的 console 摘要块(替代原 daily.ts 里那 6 行手写摘要) */
export function 格式化摘要(汇总: 汇总结果, 结果: '完成' | '已停止'): string {
  var 行: string[] = []
  行.push('')
  行.push('================================')
  行.push(结果 === '完成' ? '   日常任务 — 完成' : '   日常任务 — 已停止')
  行.push('   成功: ' + 汇总.成功 + ' | 跳过: ' + 汇总.跳过 + ' | 异常: ' + 汇总.异常 + ' | 合计: ' + 汇总.条数)
  行.push('================================')
  return 行.join('\n')
}

function 取明细(汇总: 汇总结果, 状态: '跳过' | '异常'): 明细项[] {
  var 结果: 明细项[] = []
  for (var i = 0; i < 汇总.明细.length; i++) {
    if (汇总.明细[i].状态 === 状态) 结果.push(汇总.明细[i])
  }
  return 结果
}

function 追加节(行: string[], 标题: string, 项: 明细项[], 上限: number): void {
  行.push(标题 + ' ' + 项.length + ' 项')
  var 显示数 = 上限 < 0 || 项.length <= 上限 ? 项.length : 上限
  for (var i = 0; i < 显示数; i++) {
    行.push('· ' + 格式化明细行(项[i]))
  }
  if (显示数 < 项.length) {
    行.push('… 其余 ' + (项.length - 显示数) + ' 项见「结果」页')
  }
}

function 格式化明细行(项: 明细项): string {
  var 服前缀 = 项.服 ? '[' + 项.服 + '] ' : ''
  var 原因 = 项.原因 ? 项.原因 : '未知原因'
  return 服前缀 + 项.名 + ' — ' + 原因
}
