for (var i7 = 1; i7 <= 6; i7++) 跳过('跳过' + i7)
for (var i8 = 1; i8 <= 7; i8++) 异常('异常' + i8)
var 双节 = 格式化通知明细(本轮汇总())
assert(双节.indexOf('跳过 6 项') >= 0, '跳过节标题带真实条数, 实际 [' + 双节 + ']')
assert(双节.indexOf('异常 7 项') >= 0, '异常节标题带真实条数')
assert(双节.indexOf('… 其余 1 项见运行日志') >= 0 && 双节.indexOf('… 其余 2 项见运行日志') >= 0,
  '两节各自折叠, 实际 [' + 双节 + ']')

console.log('')
console.log('--- 摘要: 整轮结束时的日志块 ---')
发布({ 类型: '本轮开始' })
成功('A'); 跳过('B', '入口未找到'); 异常('C', 'NavigationError: 示例')
var 完成摘要 = 格式化摘要(本轮汇总(), '完成')
assert(完成摘要.indexOf('日常任务 — 完成') >= 0, '完成摘要含标题, 实际 [' + 完成摘要 + ']')
assert(完成摘要.indexOf('成功: 1 | 跳过: 1 | 异常: 1 | 合计: 3') >= 0, '完成摘要含四项计数')
var 停止摘要 = 格式化摘要(本轮汇总(), '已停止')
assert(停止摘要.indexOf('日常任务 — 已停止') >= 0, '已停止摘要含对应标题, 实际 [' + 停止摘要 + ']')
assert(停止摘要.indexOf('日常任务 — 完成') < 0, '已停止摘要不含完成字样')

summary()
