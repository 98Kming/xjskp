assert(缺失文本.indexOf('undefined') < 0, '不出现 undefined, 实际 [' + 缺失文本 + ']')

console.log('')
console.log('--- 文案: 带服务器前缀 ---')
发布({ 类型: '本轮开始' })
跳过('军团 每日一刀', '未找到入口', 'S123')
