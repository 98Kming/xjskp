console.log('')
console.log('--- 边界: 6 条跳过 ---')
发布({ 类型: '本轮开始' })
for (var i6 = 1; i6 <= 6; i6++) 跳过('任务' + i6, '原因' + i6)
var 六条 = 格式化通知明细(本轮汇总())
assert(六条.indexOf('任务5') >= 0, '第 5 条仍列出')
